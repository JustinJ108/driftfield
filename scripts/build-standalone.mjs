import { readFile, writeFile, stat } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

/**
 * Turn the Vite build output into one HTML file that runs from `file://`.
 *
 * Browsers block `<script type="module" src="...">` on file:// URLs (CORS), and
 * the built HTML points at /assets/... which is also wrong for a local file.
 * Inlining makes the page self-contained: no server, no network, no paths.
 */

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const distDir = join(root, 'standalone', 'dist');
const outFile = join(root, 'Driftfield.html');

const html = await readFile(join(distDir, 'index.html'), 'utf8');

/** Keep inline script bodies from closing their own tag early. */
const safeForScript = (js) => js.replace(/<\/script/gi, '<\\/script');

const readAsset = async (href) => {
  const clean = href.replace(/^\.?\//, '').split('?')[0];
  return readFile(join(distDir, clean), 'utf8');
};

// NOTE: every replace below passes a function. String replacements interpret
// `$&`, `$\`` and friends in the *replacement*, and minified JS/CSS contains
// those sequences, which silently splices the document into itself.
let inlined = html;
const report = [];
const scripts = [];

// <script type="module" crossorigin src="./app.js"></script>
//
// The bundle is emitted as a module and Vite hoists it into <head>. A classic
// inline copy there would run before <body> exists, so the tags are dropped
// and the code is re-inserted at the end of the body instead.
const scriptTags = [...inlined.matchAll(/<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>/gi)];
for (const [tag, src] of scriptTags) {
  const js = await readAsset(src);
  scripts.push(`<script>\n${safeForScript(js)}\n</script>`);
  inlined = inlined.replace(tag, () => '');
  report.push(`inline script ${src} (${(js.length / 1024).toFixed(0)} kB)`);
}
if (scripts.length > 0) {
  const block = scripts.join('\n');
  inlined = inlined.includes('</body>')
    ? inlined.replace('</body>', () => `${block}\n  </body>`)
    : `${inlined}\n${block}`;
}

// <link rel="stylesheet" crossorigin href="./app.css">
const linkTags = [...inlined.matchAll(/<link\b[^>]*\brel="stylesheet"[^>]*>/gi)];
for (const [tag] of linkTags) {
  const href = tag.match(/\bhref="([^"]+)"/i)?.[1];
  if (!href) continue;
  const css = await readAsset(href);
  inlined = inlined.replace(tag, () => `<style>\n${css}\n</style>`);
  report.push(`inline stylesheet ${href} (${(css.length / 1024).toFixed(0)} kB)`);
}

const leftovers = [...inlined.matchAll(/\b(?:src|href)="(?!data:|#|https?:)([^"]+)"/gi)].map(
  (m) => m[1],
);
if (leftovers.length > 0) {
  throw new Error(`Refusing to ship a file:// page with external references: ${leftovers.join(', ')}`);
}

const banner = `<!--
  Driftfield — standalone build. Double-click this file to play.
  Generated by scripts/build-standalone.mjs; edit the source in src/ instead.
-->`;
inlined = inlined.replace('<!doctype html>', () => `<!doctype html>\n${banner}`);

await writeFile(outFile, inlined);

// `dist/` is the served build; dropping the same file next to it means someone
// who opens dist/index.html from disk is handed the playable copy as well.
const distEntry = join(root, 'dist', 'Driftfield.html');
try {
  await stat(join(root, 'dist'));
  await writeFile(distEntry, inlined);
  report.push(`copied to ${distEntry}`);
} catch {
  // No dist build present; nothing to mirror.
}

const { size } = await stat(outFile);
console.log(report.join('\n'));
console.log(`\nwrote ${outFile} (${(size / 1024).toFixed(0)} kB)`);
